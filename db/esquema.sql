-- Fuente única del esquema. `npm run migraciones` lo parte en archivos de
-- db/migrations/ (una sentencia por archivo).
-- Cada bloque empieza con una línea `-- @@ nombre_del_archivo`.
-- No se usa RLS con políticas: ninguna tabla se expone al query builder; solo
-- las funciones del servidor (con la URL de la base) leen y escriben.

-- @@ extension_pg_trgm
CREATE EXTENSION IF NOT EXISTS pg_trgm

-- @@ tabla_categorias
CREATE TABLE IF NOT EXISTS categorias (
  id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  nombre text NOT NULL UNIQUE,
  nombre_normalizado text NOT NULL UNIQUE,
  estado text NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'propuesta', 'inactiva')),
  creada_por text NOT NULL DEFAULT 'sistema',
  confirmada_por text,
  creada_en timestamptz NOT NULL DEFAULT now()
)

-- @@ tabla_tarjetas
CREATE TABLE IF NOT EXISTS tarjetas (
  id text PRIMARY KEY,
  nombre text NOT NULL,
  banco text NOT NULL,
  clase text NOT NULL DEFAULT 'credito' CHECK (clase IN ('credito', 'debito')),
  tipo text NOT NULL CHECK (tipo IN ('individual', 'compartida')),
  ultimos_4 text UNIQUE CHECK (ultimos_4 ~ '^[0-9]{4}$'),
  persona_default text CHECK (persona_default IN ('miguel', 'katerine')),
  activa boolean NOT NULL DEFAULT true,
  CHECK (tipo = 'compartida' OR persona_default IS NOT NULL)
)

-- @@ tabla_comercios
CREATE TABLE IF NOT EXISTS comercios (
  id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  nombre text NOT NULL UNIQUE,
  patrones text[] NOT NULL,
  categoria_semilla_id integer REFERENCES categorias(id),
  verificado boolean NOT NULL DEFAULT false,
  creado_en timestamptz NOT NULL DEFAULT now()
)

-- @@ tabla_comercios_genericos
CREATE TABLE IF NOT EXISTS comercios_genericos (
  patron text PRIMARY KEY
)

-- @@ tabla_reglas_comercio
CREATE TABLE IF NOT EXISTS reglas_comercio (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comercio_id integer NOT NULL UNIQUE REFERENCES comercios(id),
  categoria_id integer REFERENCES categorias(id),
  persona_default text CHECK (persona_default IN ('miguel', 'katerine')),
  reembolsable_default boolean,
  estado text NOT NULL DEFAULT 'propuesta' CHECK (estado IN ('propuesta', 'confirmada')),
  coincidencias_humanas integer NOT NULL DEFAULT 0,
  ultimo_movimiento_id uuid,
  creada_por text NOT NULL,
  confirmada_por text,
  confirmada_en timestamptz,
  creada_en timestamptz NOT NULL DEFAULT now(),
  actualizada_en timestamptz NOT NULL DEFAULT now()
)

-- @@ tabla_correos
CREATE TABLE IF NOT EXISTS correos (
  correo_id text PRIMARY KEY,
  remitente text NOT NULL DEFAULT '',
  asunto text NOT NULL DEFAULT '',
  fecha_correo timestamptz NOT NULL DEFAULT now(),
  banco text,
  tipo text CHECK (tipo IN ('compra', 'reverso', 'rechazo', 'otro')),
  resultado_parser text CHECK (resultado_parser IN ('ok', 'fallo')),
  fuente_interpretacion text CHECK (fuente_interpretacion IN ('regex', 'llm_cuarentena')),
  intentos_extractor integer NOT NULL DEFAULT 0,
  estado text NOT NULL DEFAULT 'recibido'
    CHECK (estado IN ('recibido', 'procesado', 'sin_pareja', 'ignorado', 'requiere_revision')),
  texto text NOT NULL DEFAULT '',
  error text,
  recibido_en timestamptz NOT NULL DEFAULT now()
)

-- @@ tabla_movimientos
CREATE TABLE IF NOT EXISTS movimientos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  correo_id text UNIQUE REFERENCES correos(correo_id),
  fecha date,
  comercio_id integer REFERENCES comercios(id),
  descripcion_original text NOT NULL DEFAULT '',
  valor bigint CHECK (valor > 0),
  cuotas integer NOT NULL DEFAULT 1 CHECK (cuotas BETWEEN 1 AND 48),
  tarjeta_id text REFERENCES tarjetas(id),
  persona text CHECK (persona IN ('miguel', 'katerine')),
  categoria_id integer REFERENCES categorias(id),
  reembolsable boolean NOT NULL DEFAULT false,
  estado text NOT NULL CHECK (estado IN (
    'requiere_interpretacion', 'provisional', 'requiere_revision', 'por_preguntar',
    'en_proceso', 'esperando_respuesta', 'confirmado', 'descartado')),
  motivo_descarte text CHECK (motivo_descarte IN ('rechazada', 'reversada', 'duplicada', 'no_reconocida', 'otro')),
  fuente text NOT NULL DEFAULT 'correo' CHECK (fuente IN ('correo', 'extracto', 'manual')),
  fuente_interpretacion text CHECK (fuente_interpretacion IN ('regex', 'llm_cuarentena')),
  confianza numeric,
  regla_id integer REFERENCES reglas_comercio(id),
  clasificado_por text CHECK (clasificado_por IN ('sistema', 'agente', 'miguel', 'katerine')),
  pregunta_codigo text,
  pregunta_texto text,
  whatsapp_message_id text,
  preguntado_a text CHECK (preguntado_a IN ('miguel', 'katerine', 'grupo')),
  destino text CHECK (destino IN ('grupo', 'privado')),
  preguntado_en timestamptz,
  recordado boolean NOT NULL DEFAULT false,
  en_proceso_hasta timestamptz,
  nota text,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now()
)

-- @@ indice_movimientos_estado
CREATE INDEX IF NOT EXISTS movimientos_estado_idx ON movimientos (estado, creado_en)

-- @@ indice_movimientos_fecha
CREATE INDEX IF NOT EXISTS movimientos_fecha_idx ON movimientos (fecha)

-- @@ indice_movimientos_codigo
CREATE UNIQUE INDEX IF NOT EXISTS movimientos_codigo_abierto_idx ON movimientos (pregunta_codigo)
  WHERE estado IN ('en_proceso', 'esperando_respuesta')

-- @@ tabla_config
CREATE TABLE IF NOT EXISTS config (
  clave text PRIMARY KEY,
  valor jsonb NOT NULL
)

-- @@ tabla_bitacora
CREATE TABLE IF NOT EXISTS bitacora (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  movimiento_id uuid,
  actor text NOT NULL CHECK (actor IN ('sistema', 'agente', 'miguel', 'katerine')),
  instruido_por text,
  accion text NOT NULL,
  antes jsonb,
  despues jsonb,
  modelo text,
  sesion_openclaw text,
  creado_en timestamptz NOT NULL DEFAULT now()
)

-- @@ indice_bitacora_movimiento
CREATE INDEX IF NOT EXISTS bitacora_movimiento_idx ON bitacora (movimiento_id)

-- @@ tabla_tokens_reclasificacion
CREATE TABLE IF NOT EXISTS tokens_reclasificacion (
  token text PRIMARY KEY,
  huella text NOT NULL,
  cantidad integer NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  expira_en timestamptz NOT NULL,
  usado_en timestamptz
)

